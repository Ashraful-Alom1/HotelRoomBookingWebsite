export async function seedInitialDatabaseIfNeeded(): Promise<{ seeded: boolean; count: number }> {
  try {
    const { collection, getDocs, addDoc } = await import("firebase/firestore");
    const { db } = await import("@/lib/firebase/client");
    const roomsRef = collection(db, "rooms");
    const snapshot = await getDocs(roomsRef);

    if (snapshot.size === 0) {
      let count = 0;
      for (const room of INITIAL_ROOMS_DATA) {
        await addDoc(roomsRef, {
          ...room,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString(),
        });
        count++;
      }
      return { seeded: true, count };
    }
    return { seeded: false, count: snapshot.size };
  } catch (error) {
    console.warn("Firestore seed skipped/failed:", error);
    return { seeded: false, count: INITIAL_ROOMS_DATA.length };
  }
}
